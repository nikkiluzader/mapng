#!/usr/bin/env python3
"""Where each official texture MapNG's materials use really is, for link files (services/textureLinkTargets.js).

MapNG links official textures into a level through link files, as BeamNG's Link Files page asks (refs/beamng-docs/
Link Files.md), but only those the game ships as a real file under exactly the material's name. The game ships many
textures as link files itself (levels/jungle_rock_island/.../t_tro_vines_b.color.png.link -> /assets/...): a MapNG
link to such a path, or to where its chain ends, left the texture missing in game (2026-11-24, docs/known-issues.md).
Those stay direct references; the game's own links resolve them.

Texture paths are collected from MapNG's material sources: public/beamng_shape_materials.json and the services'
JS. Re-run after a game update and after the material libraries change (as the other generators).

    python scripts/build-texture-link-targets.py
"""
import glob
import json
import os
import re
import zipfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.path.join(REPO, 'refs', 'beamng', 'content')
OUT = os.path.join(REPO, 'services', 'textureLinkTargets.js')
TEX = re.compile(r'["\'`]/?(levels/[A-Za-z0-9_]+/[^"\'`\s]+?\.(?:dds|png|jpe?g))["\'`]', re.I)


def used_texture_paths():
    found = set()
    srcs = [os.path.join(REPO, 'public', 'beamng_shape_materials.json')] + glob.glob(os.path.join(REPO, 'services', '*.js'))
    for p in srcs:
        if p.endswith('textureLinkTargets.js'):
            continue
        with open(p, encoding='utf-8', errors='replace') as f:
            for m in TEX.finditer(f.read()):
                found.add(m.group(1).lower())
    return found


def game_files():
    real = set()
    links = {}
    for zp in glob.glob(os.path.join(GAME, '**', '*.zip'), recursive=True):
        try:
            z = zipfile.ZipFile(zp)
        except zipfile.BadZipFile:
            continue
        for n in z.namelist():
            low = n.lower()
            if low.endswith('.link'):
                try:
                    links[low[:-5]] = json.loads(z.read(n)).get('path', '').lstrip('/').lower()
                except (ValueError, KeyError):
                    pass
            elif not low.endswith('/'):
                real.add(low)
    return real, links


def resolve(path, real, links):
    """The path itself when the game ships a real file under exactly that name, else None (left direct).

    Tried 2026-11-24 and dropped: following the game's own link chain to its end and linking there. For textures the
    game itself reaches through a link (113 of 210, often a .png name whose cooked .dds lives in /assets), a MapNG link
    to that end left them missing ("Missing source texture" in beamng.log; the same level with direct paths had
    none). Those keep their direct path, and the game's own link files do the linking for them."""
    return path if path in real else None


def main():
    if not os.path.isdir(GAME):
        raise SystemExit(f'no game content at {GAME} (is refs/beamng linked to the game?)')
    used = used_texture_paths()
    real, links = game_files()
    table = {}
    unresolved = []
    for p in sorted(used):
        target = resolve(p, real, links)
        if target:
            table[p] = target
        else:
            unresolved.append(p)
    lines = [
        '// GENERATED by scripts/build-texture-link-targets.py from the game\'s files: do not edit by hand.',
        '// Official texture path MapNG\'s materials use -> the real file it ends at (the game\'s own link files followed).',
        '// A path not listed stays a direct reference in the export (no link): see the script for why.',
        f'// {len(table)} resolved, {len(unresolved)} left direct, of {len(used)} texture paths in MapNG\'s materials.',
        'export const TEXTURE_LINK_TARGETS = {',
    ]
    for k, v in table.items():
        lines.append(f'  {json.dumps(k)}: {json.dumps(v)},')
    lines.append('};')
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{len(table)} texture paths resolved ({sum(1 for k, v in table.items() if k != v)} through the game\'s own links), '
          f'{len(unresolved)} left direct -> {os.path.relpath(OUT, REPO)}')
    for p in unresolved[:10]:
        print('  direct:', p)


if __name__ == '__main__':
    main()
